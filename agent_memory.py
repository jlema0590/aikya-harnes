"""Explicit project memories: typed references, never task evidence or approvals."""
from __future__ import annotations
import argparse,json,math,re,time
from pathlib import Path
from agent_loop_state import safe_file,fingerprint,sha,atomic
from execution_state import locked
from docs_layout import write_document,index_paths,content


def remember(root,raw,*,approved=False,now=None):
    root=Path(root).absolute()
    now=time.time() if now is None else now
    if type(now) not in (int,float) or not math.isfinite(now) or now<0:raise ValueError('Invalid memory time')
    if approved is not True:raise ValueError('Reviewed memory content requires explicit authorization')
    if not isinstance(raw,dict) or set(raw)!={'kind','text','source','ttl_days'}:raise ValueError('Invalid memory schema')
    if raw['kind'] not in ('user','feedback','project','reference') or not isinstance(raw['text'],str) or not raw['text'].strip() or len(raw['text'])>8000 or '\x00' in raw['text']:raise ValueError('Invalid memory content/type')
    if type(raw['ttl_days']) is not int or not 1<=raw['ttl_days']<=365:raise ValueError('Memory TTL must be 1–365 days')
    source=safe_file(root,raw['source'])
    if not source.is_file():raise ValueError('Current project source is required')
    ident=sha({'kind':raw['kind'],'text':' '.join(raw['text'].split()),'source':raw['source']})[:24]
    relative='memory/'+ident+'.md';path=safe_file(root,'aikya/docs/'+relative)
    index_paths(root)
    guard=safe_file(root,'.harness/state/memory/guard').parent;guard.mkdir(parents=True,exist_ok=True)
    with locked(guard):
        if path.exists():
            note=_note(root,path)
            if not note or note['text']!=raw['text'].strip() or note['source_hash']!=fingerprint(source):raise ValueError('Custom or stale memory requires review; preserve original')
            return 'aikya/docs/'+relative
        meta={'schema':1,'id':ident,'kind':raw['kind'],'source':raw['source'],'source_hash':fingerprint(source),'created_at':time.time() if now is None else now,'ttl_days':raw['ttl_days']}
        if type(meta['created_at']) not in (int,float) or meta['created_at']<0:raise ValueError('Invalid memory time')
        write_document(root,relative,'---\n'+json.dumps(meta,ensure_ascii=False)+'\n---\n\n'+raw['text'].strip())
        _index(root)
        return 'aikya/docs/'+relative


def _note(root,path):
    try:
        if path.is_symlink() or path.stat().st_size>16000:return None
        safe_file(root,path.relative_to(root).as_posix())
        text=path.read_text()
        if not text.endswith('GENERATED BY AIKYA HARNESS\n'):return None
        head,meta,body=text.split('---',2)
        if head.strip():return None
        obj=json.loads(meta)
        if not isinstance(obj,dict) or set(obj)!={'schema','id','kind','source','source_hash','created_at','ttl_days'} or obj['schema']!=1 or obj['kind'] not in ('user','feedback','project','reference'):return None
        if type(obj['created_at']) not in (int,float) or not math.isfinite(obj['created_at']) or type(obj['ttl_days']) is not int or not 1<=obj['ttl_days']<=365:return None
        body=content(body);ident=sha({'kind':obj['kind'],'text':' '.join(body.split()),'source':obj['source']})[:24]
        if ident!=obj['id'] or path.stem!=ident:return None
        return {**obj,'text':body}
    except (ValueError,OSError,TypeError,KeyError):return None


def _index(root):
    base=root/'aikya/docs/memory';lines=[]
    for path in sorted(base.glob('*.md'))[:101]:
        if path.name=='MEMORY.md':continue
        note=_note(root,path)
        if note:lines.append('- ['+note['id']+']('+path.name+') — '+note['kind'])
    write_document(root,'memory/MEMORY.md','# Project reference memories\n\n'+ '\n'.join(lines),replace_generated=True)


def recall(root,query,budget_chars,*,now=None):
    if type(budget_chars) is not int or not 0<=budget_chars<=16000:raise ValueError('Invalid total memory budget')
    if not isinstance(query,str) or len(query)>10000:raise ValueError('Invalid memory query')
    if budget_chars==0:return ''
    root=Path(root).absolute();base=safe_file(root,'aikya/docs/memory/MEMORY.md').parent
    moment=time.time() if now is None else now;words=set(re.findall(r'\w+',query.lower()));candidates=[]
    for path in sorted(base.glob('*.md'))[:101]:
        if path.name=='MEMORY.md':continue
        note=_note(root,path)
        if not note or moment<note['created_at'] or moment>=note['created_at']+note['ttl_days']*86400:continue
        try:current=fingerprint(safe_file(root,note['source']))
        except (ValueError,OSError):continue
        if current!=note['source_hash']:continue
        score=len(words&set(re.findall(r'\w+',note['text'].lower())))
        if score:candidates.append((-score,note['id'],note['text']))
    chunks=[];remaining=budget_chars
    for _,ident,text in sorted(candidates)[:5]:
        chunk=('\n' if chunks else '')+'[reference '+ident+'] '+text
        chunks.append(chunk[:remaining]);remaining-=len(chunks[-1])
        if not remaining:break
    return ''.join(chunks)


def main(argv=None):
    p=argparse.ArgumentParser(description='Reviewed project reference memories');p.add_argument('action',choices=('add','recall'));p.add_argument('--root',type=Path,default=Path.cwd());p.add_argument('--input',type=Path);p.add_argument('--query',default='');p.add_argument('--budget-chars',type=int,default=4000);p.add_argument('--approved',action='store_true');a=p.parse_args(argv)
    try:
        if a.action=='recall':result=recall(a.root,a.query,a.budget_chars)
        else:
            if not a.input or a.input.is_symlink() or not a.input.is_file() or a.input.stat().st_size>20000:raise ValueError('Reviewed regular JSON input required')
            result=remember(a.root,json.loads(a.input.read_text()),approved=a.approved)
        print(json.dumps({'result':result},ensure_ascii=False));return 0
    except (ValueError,OSError,TypeError,KeyError) as exc:print('ERROR: '+str(exc));return 2
if __name__=='__main__':raise SystemExit(main())
