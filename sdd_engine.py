#!/usr/bin/env python3
"""Portable SDD specification lifecycle and evidence records.

This module never generates application code, executes external checks or deploys.
Authorized platform agents perform changes; the engine records their workflow.
"""
from __future__ import annotations
import argparse
import json
import re
import sys
from pathlib import Path
from docs_layout import content, generated, stamp, safe, index_paths, update_index, write_document
from sdd_templates import SPEC_TEMPLATES, catalog, normalize_sections, render_sections, source_note, starter

KINDS=("development","infrastructure","devops")
ID_RE=re.compile(r"^SPEC-[0-9]{3,6}$")
REQ_RE=re.compile(r"^(REQ|INF|DEVOPS)-[0-9]{3,6}$")
TASK_RE=re.compile(r"^TASK-[0-9]{3,6}$")
STAGES=("spec","plan","tasks")
MARK="<!-- GENERATED BY AIKYA SDD 6.1.1 -->\n"

class SddError(ValueError):
    pass

def require(condition, message):
    if not condition:
        raise SddError(message)

def clean(value, label, limit=4000):
    require(isinstance(value,str) and bool(value.strip()), label+" must be non-empty text")
    require(len(value)<=limit and "\x00" not in value, label+" is too long or invalid")
    return value.strip()

def line(value):
    return str(value).replace("\r"," ").replace("\n"," ").replace("|","/").strip()

def items(raw,label):
    require(isinstance(raw,list),label+" must be a list")
    return raw

def rel_file(root, relative, must_exist=False):
    require(isinstance(relative,str) and relative and len(relative)<=240, "Invalid evidence path")
    candidate=Path(relative)
    require(not candidate.is_absolute() and ".." not in candidate.parts and not any(p in (".","") for p in relative.split("/")),
            "Path outside project or invalid")
    # Reject symlink traversal and paths outside the project.
    target=root/candidate
    for part in [target,*target.parents]:
        if part==root.parent:break
        require(not part.is_symlink(),"Symlinked paths are not allowed: "+relative)
    require(target.resolve().is_relative_to(root.resolve()),"Path outside project")
    if must_exist:
        require(target.is_file(),"Missing evidence file: "+relative)
    return target

def location(root,kind,ident):
    require(kind in KINDS,"Invalid project_type")
    require(isinstance(ident,str) and bool(ID_RE.fullmatch(ident)),"Expected SPEC-NNN identifier")
    return root/"aikya/docs/specs"/kind/ident

def read_json(path):
    require(path.is_file() and not path.is_symlink(),"Missing or symlinked JSON file: "+str(path))
    try:
        data=json.loads(path.read_text(encoding="utf-8"))
    except (ValueError,UnicodeError) as exc:
        raise SddError("Invalid JSON: "+str(exc)) from exc
    require(isinstance(data,dict),"JSON input must be an object")
    return data

def load_profile(root):
    info=read_json(root/".harness/project-profile.json")
    profile=info.get("decisions",info)
    require(isinstance(profile,dict),"Invalid Aikya profile")
    kind=profile.get("project_type","development")
    require(kind in KINDS,"Invalid project type")
    return kind,profile

def load(root,ident):
    kind,profile=load_profile(root)
    folder=location(root,kind,ident)
    rel_file(root, (folder/"state.json").relative_to(root).as_posix(), must_exist=True)
    require(profile.get("methodology", "standard") == "sdd", "SDD must be explicitly enabled")
    data=read_json(folder/"state.json")
    require(data.get("id")==ident and data.get("kind")==kind and data.get("schema")==1,
            "SDD state is incompatible with the project")
    errors = validate_state(data)
    require(not errors, "; ".join(errors))
    return folder,data

def save(root,folder,data,files,*,verification_invalidated=False):
    # Validate all destinations before writing; preserve unowned documents.
    require(not validate_state(data), "; ".join(validate_state(data)))
    if data.get("docs_language") == "es":
        from sdd_localization import localize_sdd
        files = {name: localize_sdd(body) for name, body in files.items()}
    index_paths(root)
    from docs_language import resolve
    resolve(root)  # Validate the policy before any document changes.
    destinations={folder/name:stamp(body) for name,body in files.items()}
    if verification_invalidated and data.get('verification') is None:
        for name in ('verification.md','evidence.md'):
            target=folder/name
            if target in destinations and not target.exists():destinations.pop(target)
            elif target.exists():
                body='# Verification invalidated — '+data['id']+'\n\nTask progress changed; previous results are no longer current. Re-run and record the relevant checks before claiming completion.'
                if data.get('docs_language')=='es':body=localize_sdd(body)
                destinations[target]=stamp(body)
    destinations[folder/"state.json"]=json.dumps(data,indent=2,ensure_ascii=False)+"\n"
    for target,body in destinations.items():
        rel=target.relative_to(root).as_posix()
        rel_file(root,rel)
        if target.exists():
            current=target.read_text(encoding="utf-8")
            if target.name!="state.json":
                require(generated(current),"Customized document is protected: "+rel)
            else:
                require(json.loads(current).get("id")==data["id"],
                        "Unmanaged existing SDD state: "+rel)
    for target in destinations:
        temporary=target.with_name(target.name+'.aikya-tmp')
        require(not temporary.exists() and not temporary.is_symlink(),'Temporary file already exists: '+str(temporary))
    folder.mkdir(parents=True,exist_ok=True)
    for target,body in destinations.items():
        target.parent.mkdir(parents=True,exist_ok=True)
        temp=target.with_name(target.name+".aikya-tmp")
        require(not temp.exists() and not temp.is_symlink(),"Temporary file already exists: "+str(temp))
        try:
            temp.write_text(body,encoding="utf-8")
            temp.replace(target)
        finally:
            if temp.exists():temp.unlink()
    update_index(root)

def fields_spec(data):
    ident=clean(data.get("id"),"id",20)
    require(bool(ID_RE.fullmatch(ident)),"id must be SPEC-NNN")
    title=clean(data.get("title"),"title",160)
    objective=clean(data.get("objective"),"objective",3500)
    reqs=items(data.get("requirements"),"requirements")
    require(len(reqs)>0 and len(reqs)<=100,"Between 1 and 100 requirements are required")
    output=[]
    seen=set()
    for req in reqs:
        require(isinstance(req,dict),"Requirement must be an object")
        key=clean(req.get("id"),"requirement.id",20)
        require(bool(REQ_RE.fullmatch(key)) and key not in seen,"Invalid or duplicate requirement ID: "+key)
        seen.add(key)
        description=clean(req.get("description"),"description",2000)
        acceptance=[clean(x,"acceptance",1200) for x in items(req.get("acceptance"),"acceptance")]
        require(0<len(acceptance)<=30,"Every requirement needs acceptance criteria")
        output.append({"id":key,"description":description,"acceptance":acceptance})
    nonfunctional=[clean(x,"nonfunctional",1200) for x in items(data.get("nonfunctional",[]),"nonfunctional")]
    questions=[]
    for value in items(data.get("questions",[]),"questions"):
        questions.append(clean(value,"question",1000))
    require(len(set(questions))==len(questions),"Duplicate questions")
    template=data.get('template','spec')
    require(isinstance(template,str) and template in SPEC_TEMPLATES,'Unknown specification template')
    sections=normalize_sections(template,data.get('sections'))
    extra={'template':template,'sections':sections} if 'template' in data or 'sections' in data else {}
    return {"id":ident,"title":title,"objective":objective,
            "requirements":output,"nonfunctional":nonfunctional,"questions":questions,**extra}

def render_spec(data):
    out=[MARK,"# "+line(data["id"])+" — "+line(data["title"]),"",
         "## Objective","",data["objective"],"","## Requirements and acceptance",""]
    for req in data["requirements"]:
        out.extend(["### "+req["id"],"",req["description"],""])
        out+=["- AC-"+str(i).zfill(2)+": "+v for i,v in enumerate(req["acceptance"],1)]
        out.append("")
    out.extend(["## Nonfunctional requirements",""])
    out+=["- "+x for x in data["nonfunctional"]] or ["- To be agreed"]
    template=data.get('template','spec')
    out+=['',render_sections(template,data.get('sections'),data.get('docs_language','en')), '',source_note(template,data.get('docs_language','en'))]
    return stamp('\n'.join(out))

def render_clarifications(data):
    out=[MARK,"# Clarifications — "+data["id"],"",
         "Unanswered questions prevent specification approval.",""]
    for question in data["spec"]["questions"]:
        out.extend(["## "+line(question),"",data["clarifications"].get(question,"**PENDING**"),""])
    if not data["spec"]["questions"]:
        out.append("No outstanding clarifications.")
    return stamp("\n".join(out))

def render_plan(data):
    plan=data["plan"]
    out=[MARK,"# Execution plan — "+data["id"],"",
         "## Proposed design","",plan["design"],"",
         "## Technical decisions",""]
    out+=["- "+d for d in plan["decisions"]] or ["- No additional decisions"]
    out+=["","## Risks and limitations",""]
    out+=["- "+d for d in plan["risks"]] or ["- To be assessed"]
    out+=["","## Test strategy","",plan["testing"],""]
    return stamp("\n".join(out))

def render_design(data):
    plan=data['plan']
    return stamp('# Design — '+data['id']+'\n\n## Selected approach\n\n'+plan['design']+
                 '\n\n'+render_sections('design',plan.get('sections'),data.get('docs_language','en'))+
                 '\n\n'+source_note('design',data.get('docs_language','en')))


def render_tasks(data):
    out=[MARK,"# Tasks — "+data["id"],"",
         "| Task | Status | Requirements | Dependencies | Evidence |",
         "| --- | --- | --- | --- | --- |"]
    for task in data["tasks"]:
        out.append("| "+task["id"]+" — "+line(task["description"])+" | "+task["status"]+
                   " | "+", ".join(task["requirements"])+" | "+", ".join(task["depends_on"])+
                   " | "+", ".join(task["evidence"])+" |")
    for task in data['tasks']:
        if task.get('sections'):
            out+=['','### '+task['id'], '',render_sections('tasks',task['sections'],data.get('docs_language','en'))]
    out+=['',source_note('tasks',data.get('docs_language','en'))]
    return stamp('\n'.join(out))

def render_verification(data):
    result=data.get("verification") or {}
    out=[MARK,"# SDD verification — "+data["id"],"",
         "**Status:** "+result.get("status","NOT_VERIFIED"),"",
         "The engine checks structure and evidence file existence; it does NOT execute or certify checks.",""]
    for item in result.get("requirements",[]):
        out.extend(["## "+item["id"],"", "- Declared result: "+item["result"],
                    "- Command/check: "+item["command"],
                    "- Evidence file: "+item["evidence"],""])
    if not result.get("requirements"):
        out+=["No accepted evidence has been recorded yet.",""]
    return stamp("\n".join(out))

def render_evidence(data):
    verification=data['verification']
    return stamp(content(render_verification(data)).replace('# SDD verification','# Recorded evidence',1)+
                 '\n\n'+render_sections('evidence',verification.get('sections'),data.get('docs_language','en'))+
                 '\n\n'+source_note('evidence',data.get('docs_language','en')))


def initialize(root,input_data):
    kind,profile=load_profile(root)
    require(profile.get("methodology","standard")=="sdd",
            "Enable methodology=sdd explicitly through onboarding or a reviewed profile")
    spec=fields_spec(input_data)
    folder=location(root,kind,spec["id"])
    require(not folder.exists(),"Specification already exists: "+spec["id"])
    from docs_language import read as read_docs_language
    language = read_docs_language(root) or "en"
    data={"schema":1,"docs_language":language,"id":spec["id"],"kind":kind,"spec":spec,
          "clarifications":{},"approvals":{},"plan":None,"tasks":[],
          "verification":None}
    files={'spec.md':render_spec({**spec,'docs_language':language})}
    if spec['questions']:files['clarifications.md']=render_clarifications(data)
    save(root,folder,data,files)
    return {"id":spec["id"],"status":"SPEC_DRAFT","path":str(folder.relative_to(root))}

def clarify(root,ident,answers):
    folder,data=load(root,ident)
    require("spec" not in data["approvals"],"Specification approved: create a new specification to change it")
    require(isinstance(answers.get("answers"),dict),"answers must map questions to answers")
    requested=set(data["spec"]["questions"])
    for question,answer in answers["answers"].items():
        require(question in requested,"Unknown question: "+question)
        data["clarifications"][question]=clean(answer,"answer",2000)
    save(root,folder,data,{'clarifications.md':render_clarifications(data)} if data['spec']['questions'] else {})
    return status_data(data)

def approvals_done(data,stage):
    approval = data.get("approvals", {}).get(stage)
    return isinstance(approval, dict) and approval.get("approved") is True

def approve(root,ident,stage,actor):
    require(stage in STAGES,"Unknown stage")
    folder,data=load(root,ident)
    actor=clean(actor,"actor",120)
    require(not approvals_done(data,stage),"Stage already approved")
    if stage=="spec":
        outstanding=[q for q in data["spec"]["questions"] if q not in data["clarifications"]]
        require(not outstanding,"Outstanding clarifications: "+str(len(outstanding)))
    elif stage=="plan":
        require(approvals_done(data,"spec") and data["plan"] is not None,
                "Approved specification and complete plan are required")
    elif stage=="tasks":
        require(approvals_done(data,"plan") and data["tasks"],
                "Approved plan and defined tasks are required")
    data["approvals"][stage]={"actor":actor,"approved":True}
    save(root,folder,data,{})
    return status_data(data)

def create_plan(root,ident,raw):
    folder,data=load(root,ident)
    require(approvals_done(data,"spec"),"Approve specification before planning")
    require(not approvals_done(data,"plan"),"Approved plan cannot be modified")
    plan={"design":clean(raw.get("design"),"design"),
          "decisions":[clean(s,"decision") for s in items(raw.get("decisions",[]),"decisions")],
          "risks":[clean(s,"risk") for s in items(raw.get("risks",[]),"risks")],
          "testing":clean(raw.get("testing"),"testing")}
    if "sections" in raw:plan["sections"]=normalize_sections("design",raw["sections"])
    data["plan"]=plan
    save(root,folder,data,{"design.md":render_design(data),"plan.md":render_plan(data)})
    return status_data(data)

def create_tasks(root,ident,raw):
    folder,data=load(root,ident)
    require(approvals_done(data,"plan"),"Approve plan before defining tasks")
    require(not approvals_done(data,"tasks"),"Approved tasks cannot be modified")
    rawtasks=items(raw.get("tasks"),"tasks")
    require(0<len(rawtasks)<=120,"Between 1 and 120 tasks are required")
    tasks=[]
    seen=set()
    valid_req={r["id"] for r in data["spec"]["requirements"]}
    for entry in rawtasks:
        require(isinstance(entry,dict),"Task must be an object")
        key=clean(entry.get("id"),"task.id",25)
        require(bool(TASK_RE.fullmatch(key)) and key not in seen,"Invalid or duplicate task ID")
        seen.add(key)
        refs=items(entry.get("requirements"),"task.requirements")
        require(bool(refs) and set(refs).issubset(valid_req),"Task must reference existing requirements")
        deps=items(entry.get("depends_on",[]),"depends_on")
        require(all(isinstance(dep,str) and bool(TASK_RE.fullmatch(dep)) for dep in deps),
                "Invalid dependencies")
        tasks.append({"id":key,"description":clean(entry.get("description"),"description",1500),
                      "requirements":refs,"depends_on":deps,"status":"todo","evidence":[],
                      **({"sections":normalize_sections("tasks",entry["sections"])} if "sections" in entry else {})})
    byid={t["id"]:t for t in tasks}
    require(all(set(t["depends_on"]).issubset(byid) and t["id"] not in t["depends_on"]
                for t in tasks),"Circular or missing dependency")
    def visit(key,stack,visited):
        require(key not in stack,"Cyclic dependencies")
        if key in visited:return
        for dep in byid[key]["depends_on"]:visit(dep,stack|{key},visited)
        visited.add(key)
    seen_walk=set()
    for key in byid:visit(key,set(),seen_walk)
    covered={x for t in tasks for x in t["requirements"]}
    require(covered==valid_req,"Every requirement needs at least one task; missing: "+", ".join(sorted(valid_req-covered)))
    data["tasks"]=tasks
    save(root,folder,data,{"tasks.md":render_tasks(data)})
    return status_data(data)

def progress(root,ident,task_id,result,evidence):
    folder,data=load(root,ident)
    require(approvals_done(data,"tasks"),"Approve tasks before implementation")
    task=next((t for t in data["tasks"] if t["id"]==task_id),None)
    require(task is not None,"Task not found")
    require(result in ("in_progress","done"),"Allowed status is in_progress or done")
    byid={t["id"]:t for t in data["tasks"]}
    require(all(byid[d]["status"]=="done" for d in task["depends_on"]),
            "Complete task dependencies first")
    if result=="done":
        require(evidence,"Completing a task requires an existing evidence file")
        rel_file(root,evidence,must_exist=True)
        task["evidence"]=sorted(set(task["evidence"]+[evidence]))
    task["status"]=result
    # A task change invalidates the previous verification record.
    data["verification"]=None
    save(root,folder,data,{"tasks.md":render_tasks(data)},verification_invalidated=True)
    return status_data(data)

def verify(root,ident,raw):
    folder,data=load(root,ident)
    require(approvals_done(data,"tasks"),"Tasks are not approved")
    require(all(t["status"]=="done" for t in data["tasks"]),
            "Tasks are incomplete")
    entries=items(raw.get("requirements"),"verification.requirements")
    expected={r["id"] for r in data["spec"]["requirements"]}
    seen=set()
    verified=[]
    for entry in entries:
        require(isinstance(entry,dict),"Result must be an object")
        key=clean(entry.get("id"),"verification.id",25)
        require(key in expected and key not in seen,"Invalid or duplicate evidence ID")
        seen.add(key)
        command=clean(entry.get("command"),"verification.command",800)
        result=entry.get("result")
        require(result in ("passed","failed"),"Declared result must be passed/failed")
        evidence=clean(entry.get("evidence"),"verification.evidence",240)
        rel_file(root,evidence,must_exist=True)
        verified.append({"id":key,"command":command,"result":result,"evidence":evidence})
    require(seen==expected,"Missing requirement evidence: "+", ".join(sorted(expected-seen)))
    complete=all(e["result"]=="passed" for e in verified)
    data["verification"]={"status":"EVIDENCE_RECORDED" if complete else "FAILED",
                          "requirements":verified,"independently_executed":False}
    if 'sections' in raw:data['verification']['sections']=normalize_sections('evidence',raw['sections'])
    save(root,folder,data,{'verification.md':render_verification(data),'evidence.md':render_evidence(data)})
    return status_data(data)

def status_data(data):
    approvals=data["approvals"]
    if data.get("verification"):
        step=data["verification"]["status"]
    elif "tasks" in approvals:
        step="IMPLEMENTING"
    elif data["tasks"]:
        step="TASKS_DRAFT"
    elif "plan" in approvals:
        step="PLAN_APPROVED"
    elif data["plan"] is not None:
        step="PLAN_DRAFT"
    elif "spec" in approvals:
        step="SPEC_APPROVED"
    else:step="SPEC_DRAFT"
    return {"id":data["id"],"project_type":data["kind"],
            "phase":step,"approved":sorted(approvals),
            "outstanding_questions":len([q for q in data["spec"]["questions"]
                                         if q not in data["clarifications"]]),
            "total_tasks":len(data["tasks"]),
            "completed_tasks":len([t for t in data["tasks"] if t["status"]=="done"]),
            "requirements":len(data["spec"]["requirements"])}

def validate_state(data):
    """Recheck persisted records, including edits and merge results, on every load."""
    errors = []
    try:
        require(isinstance(data, dict) and data.get("schema") == 1, "Unsupported SDD state schema")
        require(data.get("kind") in KINDS, "Invalid project type")
        require(bool(ID_RE.fullmatch(str(data.get("id", "")))), "Invalid specification ID")
        spec = fields_spec(data.get("spec", {}))
        require(spec["id"] == data["id"], "Specification ID mismatch")
        answers = data.get("clarifications")
        require(isinstance(answers, dict) and set(answers).issubset(spec["questions"]), "Invalid clarifications")
        for answer in answers.values(): clean(answer, "answer", 2000)
        approvals = data.get("approvals")
        require(isinstance(approvals, dict) and set(approvals).issubset(STAGES), "Invalid approvals")
        for stage, approval in approvals.items():
            require(isinstance(approval, dict) and approval.get("approved") is True, "Invalid approval: " + stage)
            clean(approval.get("actor"), "approval actor", 120)
        if approvals_done(data, "spec"):
            require(set(answers) == set(spec["questions"]), "Unanswered clarifications")
        plan = data.get("plan")
        if plan is not None:
            require(approvals_done(data, "spec") and isinstance(plan, dict), "Plan requires approved specification")
            clean(plan.get("design"), "design")
            clean(plan.get("testing"), "testing")
            normalize_sections("design",plan.get("sections"))
            for key in ("decisions", "risks"):
                for value in items(plan.get(key), key): clean(value, key)
        if approvals_done(data, "plan"):
            require(plan is not None, "Approved plan is missing")
        tasks = items(data.get("tasks"), "tasks")
        require(len(tasks) <= 120, "Too many tasks")
        valid_req = {r["id"] for r in spec["requirements"]}
        byid = {}; covered = set()
        for task in tasks:
            require(isinstance(task, dict), "Invalid task")
            key = task.get("id")
            require(isinstance(key, str) and bool(TASK_RE.fullmatch(key)) and key not in byid, "Invalid or duplicate task ID")
            clean(task.get("description"), "task description", 1500)
            normalize_sections("tasks",task.get("sections"))
            refs = items(task.get("requirements"), "task requirements")
            require(bool(refs) and all(isinstance(r, str) and r in valid_req for r in refs), "Unknown task requirement")
            covered.update(refs)
            deps = items(task.get("depends_on"), "dependencies")
            require(all(isinstance(d, str) and bool(TASK_RE.fullmatch(d)) for d in deps), "Invalid dependency")
            require(task.get("status") in ("todo", "in_progress", "done"), "Invalid task status")
            evidence = items(task.get("evidence"), "task evidence")
            require(all(isinstance(e, str) and e for e in evidence), "Invalid evidence paths")
            if task["status"] != "todo": require(approvals_done(data, "tasks"), "Task progress requires approval")
            if task["status"] == "done": require(bool(evidence), "Completed task requires evidence")
            byid[key] = task
        if tasks:
            require(approvals_done(data, "plan"), "Tasks require approved plan")
            require(covered == valid_req, "Tasks must cover all requirements")
        if approvals_done(data, "tasks"):
            require(approvals_done(data, "plan") and bool(tasks), "Task approval requires approved plan and tasks")
        visited = set()
        def visit(key, stack):
            require(key not in stack, "Cyclic task dependencies")
            require(key in byid, "Unknown task dependency")
            if key in visited: return
            for dep in byid[key]["depends_on"]: visit(dep, stack | {key})
            visited.add(key)
        for key, task in byid.items():
            visit(key, set())
            if task["status"] != "todo":
                require(all(byid[d]["status"] == "done" for d in task["depends_on"]), "Task dependencies are incomplete")
        verification = data.get("verification")
        if verification is not None:
            require(approvals_done(data, "tasks") and all(t["status"] == "done" for t in tasks), "Verification requires completed approved tasks")
            require(isinstance(verification, dict) and verification.get("independently_executed") is False, "Invalid verification record")
            normalize_sections("evidence",verification.get("sections"))
            entries = items(verification.get("requirements"), "verification requirements")
            found = set()
            for entry in entries:
                require(isinstance(entry, dict), "Invalid verification item")
                key = entry.get("id")
                require(isinstance(key, str) and key in valid_req and key not in found, "Invalid verification requirement")
                found.add(key)
                clean(entry.get("command"), "command", 800)
                clean(entry.get("evidence"), "evidence", 240)
                require(entry.get("result") in ("passed", "failed"), "Invalid verification result")
            require(found == valid_req, "Verification must cover all requirements")
            status = "EVIDENCE_RECORDED" if all(e["result"] == "passed" for e in entries) else "FAILED"
            require(verification.get("status") == status, "Inconsistent verification status")
    except (ValueError, TypeError, KeyError, AttributeError, RecursionError) as exc:
        errors.append(str(exc))
    return errors


def require_approved_task(root, spec_id, task_id):
    """Authorize a specific ready task, never any historical project approval."""
    require(spec_id and task_id, "SDD requires --spec-id and --task-id")
    folder, data = load(root, spec_id)
    require(all(approvals_done(data, stage) for stage in STAGES), "Specification, plan and tasks must be approved")
    task = next((t for t in data["tasks"] if t["id"] == task_id), None)
    require(task is not None, "Task not found in active specification")
    byid = {t["id"]: t for t in data["tasks"]}
    require(all(byid[d]["status"] == "done" for d in task["depends_on"]), "Complete task dependencies first")
    return task


def validate_completion(root, spec_id):
    """Check recorded completion; this never executes or certifies external tests."""
    try:
        folder, data = load(root, spec_id)
        require(all(approvals_done(data, stage) for stage in STAGES), "All stages require approval")
        require(bool(data["tasks"]) and all(t["status"] == "done" for t in data["tasks"]), "Incomplete tasks")
        require(data.get("verification") and data["verification"]["status"] == "EVIDENCE_RECORDED", "Passing requirement evidence is missing")
        for task in data["tasks"]:
            for path in task["evidence"]: rel_file(root, path, must_exist=True)
        for entry in data["verification"]["requirements"]: rel_file(root, entry["evidence"], must_exist=True)
        return []
    except (ValueError, OSError, TypeError, KeyError) as exc:
        return [str(exc)]


def validate(root):
    base=root/"aikya/docs/specs"
    try:
        rel_file(root, "aikya/docs/specs")
    except ValueError as exc:
        return {"valid":False,"specifications":0,"errors":[str(exc)]}
    if not base.exists(): return {"valid":True,"specifications":0,"errors":[]}
    errors=[];count=0
    for directory in base.glob("*/*"):
        if not directory.is_dir() and not directory.is_symlink(): continue
        file = directory/"state.json"
        count+=1
        try:
            ident=file.parent.name;kind=file.parent.parent.name
            folder=location(root,kind,ident)
            rel_file(root, file.relative_to(root).as_posix(), must_exist=True)
            data=read_json(file)
            require(data.get("id")==ident and data.get("kind")==kind, "Specification location mismatch")
            require(not validate_state(data), "; ".join(validate_state(data)))
            documents=['spec.md']
            if data['spec']['questions']:documents.append('clarifications.md')
            if data.get('verification'):documents.append('verification.md')
            for name in documents:
                rel_file(root, (folder/name).relative_to(root).as_posix(), must_exist=True)
            if data["plan"] is not None:
                for name in ("plan.md", "design.md"): rel_file(root, (folder/name).relative_to(root).as_posix(), must_exist=True)
            if data["tasks"]: rel_file(root, (folder/"tasks.md").relative_to(root).as_posix(), must_exist=True)
            for task in data["tasks"]:
                for path in task["evidence"]:rel_file(root,path,must_exist=True)
            if data.get("verification"):
                for item in data["verification"]["requirements"]:rel_file(root,item["evidence"],must_exist=True)
        except (OSError,ValueError,KeyError,TypeError) as exc:
            errors.append(str(file)+": "+str(exc))
    return {"valid":not errors,"specifications":count,"errors":errors}


def create_document(root, template, raw, *, ident=None, approved=False):
    require(approved,'Writing a template document requires explicit approval')
    require(template in ('review','constitution'),'Only review and constitution are auxiliary documents')
    kind,profile=load_profile(root)
    require(profile.get('methodology')=='sdd','SDD must be explicitly enabled')
    sections=normalize_sections(template,raw.get('sections'))
    require(bool(sections),'No document is created without reviewed content')
    if template=='review':
        require(ident,'A review requires the specification ID')
        folder,data=load(root,ident)
        relative=(folder/'review.md').relative_to(root/'aikya/docs').as_posix()
    else:
        require(not ident,'The constitution applies to the project, not one specification')
        relative='specs/constitution.md'
    from docs_language import resolve
    locale=resolve(root)
    title={'review':('Specification review','Revisión de especificación'),
           'constitution':('Engineering constitution','Constitución de ingeniería')}[template][locale=='es']
    note='This document records reviewed content; it does not approve an SDD stage.' if locale=='en' else 'Este documento registra contenido revisado; no aprueba etapas SDD.'
    body='# '+title+(' — '+ident if ident else '')+'\n\n'+note+'\n\n'+render_sections(template,sections,locale)+'\n\n'+source_note(template,locale)
    return {'path':write_document(root,relative,body,replace_generated=True),'approval_recorded':False}


def main(argv=None):
    parser=argparse.ArgumentParser(description="Aikya Spec-Driven Engineering")
    parser.add_argument("action",choices=("new","clarify","approve","plan","tasks","worklist","progress","verify","status","list","lint","completion","authorize","templates","document"))
    parser.add_argument("--root",type=Path,default=Path.cwd())
    parser.add_argument("--template",choices=tuple(catalog()))
    parser.add_argument("--approved",action="store_true")
    parser.add_argument("--id")
    parser.add_argument("--input",type=Path,help="JSON explicitly reviewed by the user")
    parser.add_argument("--stage",choices=STAGES)
    parser.add_argument("--actor")
    parser.add_argument("--task")
    parser.add_argument("--result",choices=("in_progress","done"))
    parser.add_argument("--evidence",help="Relative path of an existing evidence file")
    args=parser.parse_args(argv)
    root=args.root.expanduser().resolve()
    try:
        require(root.is_dir(),"Project does not exist")
        if args.action=='templates':
            if args.template:
                print(starter(args.template),end='')
            else:print(json.dumps(catalog(),ensure_ascii=False,indent=2))
            return 0
        if args.action=='document':
            require(args.template and args.input,'Document writing requires --template and --input')
            result=create_document(root,args.template,read_json(args.input.resolve()),ident=args.id,approved=args.approved)
        elif args.action=="lint":
            result=validate(root)
        elif args.action=="completion":
            require(args.id, "Completion requires --id")
            errors = validate_completion(root, args.id)
            print(json.dumps({"ready": not errors, "errors": errors, "independently_executed": False}))
            return 1 if errors else 0
        elif args.action=="authorize":
            result = require_approved_task(root, args.id, args.task)
        elif args.action=="list":
            kind,_=load_profile(root)
            base=root/"aikya/docs/specs"/kind
            result={"specifications":sorted(p.name for p in base.iterdir()
                        if p.is_dir() and ID_RE.fullmatch(p.name)) if base.exists() else []}
        else:
            if args.action in ("new","clarify","plan","tasks","verify"):
                require(args.input is not None,"Action requires --input JSON")
                input_data=read_json(args.input.resolve())
            if args.action=="new":
                result=initialize(root,input_data)
            else:
                require(args.id is not None,"Action requires --id SPEC-NNN")
                if args.action=="clarify":result=clarify(root,args.id,input_data)
                elif args.action=="approve":
                    require(args.stage and args.actor,"Approval requires --stage and --actor")
                    result=approve(root,args.id,args.stage,args.actor)
                elif args.action=="plan":result=create_plan(root,args.id,input_data)
                elif args.action=="tasks":result=create_tasks(root,args.id,input_data)
                elif args.action=="progress":
                    require(args.task and args.result,"Progress requires --task and --result")
                    result=progress(root,args.id,args.task,args.result,args.evidence)
                elif args.action=="verify":result=verify(root,args.id,input_data)
                elif args.action=="worklist":
                    folder,data=load(root,args.id)
                    require(approvals_done(data,"tasks"),"Tasks have not been approved")
                    result={"id":args.id,"tasks":data["tasks"],"note":"Implementation requires an authorized agent; this engine does not edit code."}
                else:
                    folder,data=load(root,args.id)
                    result=status_data(data)
        print(json.dumps(result,ensure_ascii=False,indent=2))
        return 0 if not (args.action=="lint" and not result["valid"]) else 1
    except (SddError,OSError,UnicodeError,TypeError,ValueError,KeyError) as exc:
        print("ERROR SDD: "+str(exc),file=sys.stderr)
        return 2

if __name__=="__main__":
    sys.exit(main())
