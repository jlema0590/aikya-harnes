#!/usr/bin/env python3
"""Aikya SDD 6.0.0. Motor portable de especificaciones sin ejecutores externos.

No genera código, IaC ni despliegues. Los agentes de la plataforma realizan los
cambios autorizados; este motor conserva especificación, planes, tareas y evidencias.
"""
from __future__ import annotations
import argparse
import json
import re
import sys
from pathlib import Path

KINDS=("development","infrastructure","devops")
ID_RE=re.compile(r"^SPEC-[0-9]{3,6}$")
REQ_RE=re.compile(r"^(REQ|INF|DEVOPS)-[0-9]{3,6}$")
TASK_RE=re.compile(r"^TASK-[0-9]{3,6}$")
STAGES=("spec","plan","tasks")
MARK="<!-- GENERATED BY AIKYA SDD 6.0.0 -->\n"

class SddError(ValueError):
    pass

def require(condition, message):
    if not condition:
        raise SddError(message)

def clean(value, label, limit=4000):
    require(isinstance(value,str) and bool(value.strip()), label+" debe ser texto no vacío")
    require(len(value)<=limit and "\x00" not in value, label+" demasiado largo o inválido")
    return value.strip()

def line(value):
    return str(value).replace("\r"," ").replace("\n"," ").replace("|","/").strip()

def items(raw,label):
    require(isinstance(raw,list),label+" debe ser una lista")
    return raw

def rel_file(root, relative, must_exist=False):
    require(isinstance(relative,str) and relative and len(relative)<=240, "Ruta de evidencia no válida")
    candidate=Path(relative)
    require(not candidate.is_absolute() and ".." not in candidate.parts and not any(p in (".","") for p in relative.split("/")),
            "Ruta fuera del proyecto o no válida")
    # No atravesar enlaces simbólicos ni salir del proyecto.
    target=root/candidate
    for part in [target,*target.parents]:
        if part==root.parent:break
        require(not part.is_symlink(),"No se permiten rutas simbólicas: "+relative)
    require(target.resolve().is_relative_to(root.resolve()),"Ruta fuera del proyecto")
    if must_exist:
        require(target.is_file(),"Falta archivo de evidencia: "+relative)
    return target

def location(root,kind,ident):
    require(kind in KINDS,"project_type no válido")
    require(isinstance(ident,str) and bool(ID_RE.fullmatch(ident)),"Identificador esperado SPEC-NNN")
    return root/"aikya/docs/specs"/kind/ident

def read_json(path):
    require(path.is_file() and not path.is_symlink(),"Archivo JSON no encontrado o simbólico: "+str(path))
    try:
        data=json.loads(path.read_text(encoding="utf-8"))
    except (ValueError,UnicodeError) as exc:
        raise SddError("JSON inválido: "+str(exc)) from exc
    require(isinstance(data,dict),"Entrada JSON debe ser un objeto")
    return data

def load_profile(root):
    info=read_json(root/".harness/project-profile.json")
    profile=info.get("decisions",info)
    require(isinstance(profile,dict),"Perfil Aikya inválido")
    kind=profile.get("project_type","development")
    require(kind in KINDS,"Modo de proyecto no válido")
    return kind,profile

def load(root,ident):
    kind,profile=load_profile(root)
    folder=location(root,kind,ident)
    data=read_json(folder/"state.json")
    require(data.get("id")==ident and data.get("kind")==kind and data.get("schema")==1,
            "Estado SDD incompatible con el proyecto")
    return folder,data

def save(root,folder,data,files):
    # Verificar rutas ANTES de escribir. Los documentos son propiedad de SDD;
    # no se sobrescriben archivos preexistentes sin marcador propio.
    destinations={folder/name:body for name,body in files.items()}
    destinations[folder/"state.json"]=json.dumps(data,indent=2,ensure_ascii=False)+"\n"
    for target,body in destinations.items():
        rel=target.relative_to(root).as_posix()
        rel_file(root,rel)
        if target.exists():
            current=target.read_text(encoding="utf-8")
            if target.name!="state.json":
                require(current.startswith(MARK),"Documento personalizado protegido: "+rel)
            else:
                require(json.loads(current).get("id")==data["id"],
                        "Estado SDD existente no gestionado: "+rel)
    folder.mkdir(parents=True,exist_ok=True)
    for target,body in destinations.items():
        target.parent.mkdir(parents=True,exist_ok=True)
        temp=target.with_name(target.name+".aikya-tmp")
        require(not temp.exists() and not temp.is_symlink(),"Archivo temporal existente: "+str(temp))
        try:
            temp.write_text(body,encoding="utf-8")
            temp.replace(target)
        finally:
            if temp.exists():temp.unlink()

def fields_spec(data):
    ident=clean(data.get("id"),"id",20)
    require(bool(ID_RE.fullmatch(ident)),"id debe ser SPEC-NNN")
    title=clean(data.get("title"),"title",160)
    objective=clean(data.get("objective"),"objective",3500)
    reqs=items(data.get("requirements"),"requirements")
    require(len(reqs)>0 and len(reqs)<=100,"Es necesario de 1 a 100 requisitos")
    output=[]
    seen=set()
    for req in reqs:
        require(isinstance(req,dict),"Requisito debe ser objeto")
        key=clean(req.get("id"),"requirement.id",20)
        require(bool(REQ_RE.fullmatch(key)) and key not in seen,"ID de requisito inválido o repetido: "+key)
        seen.add(key)
        description=clean(req.get("description"),"description",2000)
        acceptance=[clean(x,"acceptance",1200) for x in items(req.get("acceptance"),"acceptance")]
        require(0<len(acceptance)<=30,"Cada requisito necesita criterios de aceptación")
        output.append({"id":key,"description":description,"acceptance":acceptance})
    nonfunctional=[clean(x,"nonfunctional",1200) for x in items(data.get("nonfunctional",[]),"nonfunctional")]
    questions=[]
    for value in items(data.get("questions",[]),"questions"):
        questions.append(clean(value,"question",1000))
    require(len(set(questions))==len(questions),"Preguntas duplicadas")
    return {"id":ident,"title":title,"objective":objective,
            "requirements":output,"nonfunctional":nonfunctional,"questions":questions}

def render_spec(data):
    out=[MARK,"# "+line(data["id"])+" — "+line(data["title"]),"",
         "## Objetivo","",data["objective"],"","## Requisitos y aceptación",""]
    for req in data["requirements"]:
        out.extend(["### "+req["id"],"",req["description"],""])
        out+=["- AC-"+str(i).zfill(2)+": "+v for i,v in enumerate(req["acceptance"],1)]
        out.append("")
    out.extend(["## Requisitos no funcionales",""])
    out+=["- "+x for x in data["nonfunctional"]] or ["- Por acordar"]
    return "\n".join(out)+"\n"

def render_clarifications(data):
    out=[MARK,"# Aclaraciones — "+data["id"],"",
         "Las preguntas sin respuesta impiden aprobar la especificación.",""]
    for question in data["spec"]["questions"]:
        out.extend(["## "+line(question),"",data["clarifications"].get(question,"**PENDIENTE**"),""])
    if not data["spec"]["questions"]:
        out.append("No hay aclaraciones pendientes.")
    return "\n".join(out)+"\n"

def render_plan(data):
    plan=data["plan"]
    out=[MARK,"# Diseño y plan — "+data["id"],"",
         "## Diseño aprobado propuesto","",plan["design"],"",
         "## Decisiones técnicas",""]
    out+=["- "+d for d in plan["decisions"]] or ["- Ninguna adicional"]
    out+=["","## Riesgos y limitaciones",""]
    out+=["- "+d for d in plan["risks"]] or ["- Por evaluar"]
    out+=["","## Estrategia de pruebas","",plan["testing"],""]
    return "\n".join(out)+"\n"

def render_tasks(data):
    out=[MARK,"# Tareas — "+data["id"],"",
         "| Tarea | Estado | Requisitos | Dependencias | Evidencias |",
         "| --- | --- | --- | --- | --- |"]
    for task in data["tasks"]:
        out.append("| "+task["id"]+" — "+line(task["description"])+" | "+task["status"]+
                   " | "+", ".join(task["requirements"])+" | "+", ".join(task["depends_on"])+
                   " | "+", ".join(task["evidence"])+" |")
    return "\n".join(out)+"\n"

def render_verification(data):
    result=data.get("verification") or {}
    out=[MARK,"# Verificación SDD — "+data["id"],"",
         "**Estado:** "+result.get("status","NOT_VERIFIED"),"",
         "El motor verifica estructura y existencia de las evidencias; NO ejecuta ni certifica los checks.",""]
    for item in result.get("requirements",[]):
        out.extend(["## "+item["id"],"", "- Resultado declarado: "+item["result"],
                    "- Comando/validación: "+item["command"],
                    "- Archivo de evidencia: "+item["evidence"],""])
    if not result.get("requirements"):
        out+=["No existen evidencias aceptadas todavía.",""]
    return "\n".join(out)+"\n"

def initialize(root,input_data):
    kind,profile=load_profile(root)
    require(profile.get("methodology","standard")=="sdd",
            "Activa methodology=sdd mediante /aikya-init o /aikya-answers")
    spec=fields_spec(input_data)
    folder=location(root,kind,spec["id"])
    require(not folder.exists(),"Especificación ya existe: "+spec["id"])
    data={"schema":1,"id":spec["id"],"kind":kind,"spec":spec,
          "clarifications":{},"approvals":{},"plan":None,"tasks":[],
          "verification":None}
    save(root,folder,data,{"spec.md":render_spec(spec),
                           "clarifications.md":render_clarifications(data),
                           "verification.md":render_verification(data)})
    return {"id":spec["id"],"status":"SPEC_DRAFT","path":str(folder.relative_to(root))}

def clarify(root,ident,answers):
    folder,data=load(root,ident)
    require("spec" not in data["approvals"],"Especificación aprobada: crea una nueva spec para cambiarla")
    require(isinstance(answers.get("answers"),dict),"answers debe ser objeto pregunta: respuesta")
    requested=set(data["spec"]["questions"])
    for question,answer in answers["answers"].items():
        require(question in requested,"Pregunta no registrada: "+question)
        data["clarifications"][question]=clean(answer,"answer",2000)
    save(root,folder,data,{"clarifications.md":render_clarifications(data)})
    return status_data(data)

def approvals_done(data,stage):
    return stage in data["approvals"]

def approve(root,ident,stage,actor):
    require(stage in STAGES,"Fase desconocida")
    folder,data=load(root,ident)
    actor=clean(actor,"actor",120)
    require(not approvals_done(data,stage),"Fase ya aprobada")
    if stage=="spec":
        outstanding=[q for q in data["spec"]["questions"] if q not in data["clarifications"]]
        require(not outstanding,"Aclaraciones pendientes: "+str(len(outstanding)))
    elif stage=="plan":
        require(approvals_done(data,"spec") and data["plan"] is not None,
                "Necesitas especificación aprobada y plan completo")
    elif stage=="tasks":
        require(approvals_done(data,"plan") and data["tasks"],
                "Necesitas plan aprobado y tareas definidas")
    data["approvals"][stage]={"actor":actor,"approved":True}
    save(root,folder,data,{})
    return status_data(data)

def create_plan(root,ident,raw):
    folder,data=load(root,ident)
    require(approvals_done(data,"spec"),"Aprueba especificación antes de elaborar plan")
    require(not approvals_done(data,"plan"),"Plan aprobado: no modificarlo")
    plan={"design":clean(raw.get("design"),"design"),
          "decisions":[clean(s,"decision") for s in items(raw.get("decisions",[]),"decisions")],
          "risks":[clean(s,"risk") for s in items(raw.get("risks",[]),"risks")],
          "testing":clean(raw.get("testing"),"testing")}
    data["plan"]=plan
    save(root,folder,data,{"design.md":render_plan(data),"plan.md":render_plan(data)})
    return status_data(data)

def create_tasks(root,ident,raw):
    folder,data=load(root,ident)
    require(approvals_done(data,"plan"),"Aprueba plan antes de crear tareas")
    require(not approvals_done(data,"tasks"),"Tareas aprobadas: no modificar")
    rawtasks=items(raw.get("tasks"),"tasks")
    require(0<len(rawtasks)<=120,"Debe haber de 1 a 120 tareas")
    tasks=[]
    seen=set()
    valid_req={r["id"] for r in data["spec"]["requirements"]}
    for entry in rawtasks:
        require(isinstance(entry,dict),"Tarea debe ser un objeto")
        key=clean(entry.get("id"),"task.id",25)
        require(bool(TASK_RE.fullmatch(key)) and key not in seen,"ID de tarea inválido o duplicado")
        seen.add(key)
        refs=items(entry.get("requirements"),"task.requirements")
        require(bool(refs) and set(refs).issubset(valid_req),"Tarea debe referenciar requisitos existentes")
        deps=items(entry.get("depends_on",[]),"depends_on")
        require(all(isinstance(dep,str) and bool(TASK_RE.fullmatch(dep)) for dep in deps),
                "Dependencias no válidas")
        tasks.append({"id":key,"description":clean(entry.get("description"),"description",1500),
                      "requirements":refs,"depends_on":deps,"status":"todo","evidence":[]})
    byid={t["id"]:t for t in tasks}
    require(all(set(t["depends_on"]).issubset(byid) and t["id"] not in t["depends_on"]
                for t in tasks),"Dependencia circular o inexistente")
    def visit(key,stack,visited):
        require(key not in stack,"Dependencias cíclicas")
        if key in visited:return
        for dep in byid[key]["depends_on"]:visit(dep,stack|{key},visited)
        visited.add(key)
    seen_walk=set()
    for key in byid:visit(key,set(),seen_walk)
    covered={x for t in tasks for x in t["requirements"]}
    require(covered==valid_req,"Todos los requisitos necesitan al menos una tarea; faltan: "+", ".join(sorted(valid_req-covered)))
    data["tasks"]=tasks
    save(root,folder,data,{"tasks.md":render_tasks(data)})
    return status_data(data)

def progress(root,ident,task_id,result,evidence):
    folder,data=load(root,ident)
    require(approvals_done(data,"tasks"),"Aprueba tareas antes de implementación")
    task=next((t for t in data["tasks"] if t["id"]==task_id),None)
    require(task is not None,"Tarea no encontrada")
    require(result in ("in_progress","done"),"Estado permitido in_progress o done")
    byid={t["id"]:t for t in data["tasks"]}
    if result=="done":
        require(all(byid[d]["status"]=="done" for d in task["depends_on"]),
                "Primero completar dependencias")
        require(evidence,"Completar tarea requiere ruta de evidencia real")
        rel_file(root,evidence,must_exist=True)
        task["evidence"]=sorted(set(task["evidence"]+[evidence]))
    task["status"]=result
    # La verificación anterior deja de ser válida si cambia una tarea.
    data["verification"]=None
    save(root,folder,data,{"tasks.md":render_tasks(data),
                           "verification.md":render_verification(data)})
    return status_data(data)

def verify(root,ident,raw):
    folder,data=load(root,ident)
    require(approvals_done(data,"tasks"),"Tareas sin aprobar")
    require(all(t["status"]=="done" for t in data["tasks"]),
            "Hay tareas pendientes de terminar")
    entries=items(raw.get("requirements"),"verification.requirements")
    expected={r["id"] for r in data["spec"]["requirements"]}
    seen=set()
    verified=[]
    for entry in entries:
        require(isinstance(entry,dict),"Resultado debe ser objeto")
        key=clean(entry.get("id"),"verification.id",25)
        require(key in expected and key not in seen,"ID de evidencia inválido o duplicado")
        seen.add(key)
        command=clean(entry.get("command"),"verification.command",800)
        result=entry.get("result")
        require(result in ("passed","failed"),"Resultado declarado passed/failed")
        evidence=clean(entry.get("evidence"),"verification.evidence",240)
        rel_file(root,evidence,must_exist=True)
        verified.append({"id":key,"command":command,"result":result,"evidence":evidence})
    require(seen==expected,"Faltan evidencias de requisitos: "+", ".join(sorted(expected-seen)))
    complete=all(e["result"]=="passed" for e in verified)
    data["verification"]={"status":"EVIDENCE_RECORDED" if complete else "FAILED",
                          "requirements":verified,"independently_executed":False}
    save(root,folder,data,{"verification.md":render_verification(data)})
    return status_data(data)

def status_data(data):
    approvals=data["approvals"]
    if data.get("verification"):
        step=data["verification"]["status"]
    elif "tasks" in approvals:
        step="IMPLEMENTING"
    elif data["tasks"]:
        step="TASKS_DRAFT"
    elif "plan" in approvals:
        step="PLAN_APPROVED"
    elif data["plan"] is not None:
        step="PLAN_DRAFT"
    elif "spec" in approvals:
        step="SPEC_APPROVED"
    else:step="SPEC_DRAFT"
    return {"id":data["id"],"project_type":data["kind"],
            "phase":step,"approved":sorted(approvals),
            "outstanding_questions":len([q for q in data["spec"]["questions"]
                                         if q not in data["clarifications"]]),
            "total_tasks":len(data["tasks"]),
            "completed_tasks":len([t for t in data["tasks"] if t["status"]=="done"]),
            "requirements":len(data["spec"]["requirements"])}

def validate(root):
    base=root/"aikya/docs/specs"
    if not base.exists():return {"valid":True,"specifications":0,"errors":[]}
    errors=[];count=0
    for file in base.glob("*/*/state.json"):
        count+=1
        try:
            ident=file.parent.name
            kind=file.parent.parent.name
            folder=location(root,kind,ident)
            data=read_json(file)
            require(data.get("id")==ident and data.get("kind")==kind and data.get("schema")==1,
                    "Identificador, tipo o schema incoherente")
            require((folder/"spec.md").is_file(),"Falta spec.md")
            if data["plan"] is not None:require((folder/"plan.md").is_file(),"Falta plan.md")
            if data["tasks"]:require((folder/"tasks.md").is_file(),"Falta tasks.md")
            for task in data["tasks"]:
                for path in task["evidence"]:rel_file(root,path,must_exist=True)
            if data.get("verification"):
                for item in data["verification"]["requirements"]:
                    rel_file(root,item["evidence"],must_exist=True)
        except (OSError,ValueError,KeyError,TypeError) as exc:
            errors.append(str(file)+": "+str(exc))
    return {"valid":not errors,"specifications":count,"errors":errors}

def main(argv=None):
    parser=argparse.ArgumentParser(description="Aikya 6.0.0 Spec-Driven Engineering")
    parser.add_argument("action",choices=("new","clarify","approve","plan","tasks","worklist","progress","verify","status","list","lint"))
    parser.add_argument("--root",type=Path,default=Path.cwd())
    parser.add_argument("--id")
    parser.add_argument("--input",type=Path,help="JSON explícitamente revisado por el usuario")
    parser.add_argument("--stage",choices=STAGES)
    parser.add_argument("--actor")
    parser.add_argument("--task")
    parser.add_argument("--result",choices=("in_progress","done"))
    parser.add_argument("--evidence",help="Ruta relativa del archivo de prueba existente")
    args=parser.parse_args(argv)
    root=args.root.expanduser().resolve()
    try:
        require(root.is_dir(),"El proyecto no existe")
        if args.action=="lint":
            result=validate(root)
        elif args.action=="list":
            kind,_=load_profile(root)
            base=root/"aikya/docs/specs"/kind
            result={"specifications":sorted(p.name for p in base.iterdir()
                        if p.is_dir() and ID_RE.fullmatch(p.name)) if base.exists() else []}
        else:
            if args.action in ("new","clarify","plan","tasks","verify"):
                require(args.input is not None,"Acción requiere --input JSON")
                input_data=read_json(args.input.resolve())
            if args.action=="new":
                result=initialize(root,input_data)
            else:
                require(args.id is not None,"Acción requiere --id SPEC-NNN")
                if args.action=="clarify":result=clarify(root,args.id,input_data)
                elif args.action=="approve":
                    require(args.stage and args.actor,"Aprobación requiere --stage y --actor")
                    result=approve(root,args.id,args.stage,args.actor)
                elif args.action=="plan":result=create_plan(root,args.id,input_data)
                elif args.action=="tasks":result=create_tasks(root,args.id,input_data)
                elif args.action=="progress":
                    require(args.task and args.result,"Progreso requiere --task y --result")
                    result=progress(root,args.id,args.task,args.result,args.evidence)
                elif args.action=="verify":result=verify(root,args.id,input_data)
                elif args.action=="worklist":
                    folder,data=load(root,args.id)
                    require(approvals_done(data,"tasks"),"Aún no hay tareas aprobadas")
                    result={"id":args.id,"tasks":data["tasks"],"note":"Requiere implementar con un agente aprobado; el motor no edita código."}
                else:
                    folder,data=load(root,args.id)
                    result=status_data(data)
        print(json.dumps(result,ensure_ascii=False,indent=2))
        return 0 if not (args.action=="lint" and not result["valid"]) else 1
    except (SddError,OSError,UnicodeError,TypeError,ValueError,KeyError) as exc:
        print("ERROR SDD: "+str(exc),file=sys.stderr)
        return 2

if __name__=="__main__":
    sys.exit(main())
