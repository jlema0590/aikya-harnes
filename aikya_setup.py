def files_to_copy(source:Path):
    for name in CORE_FILES:
        yield source/name,Path(name)
    for folder in ('template','examples','aikya-skills','engineering','sdd-templates','claude-templates','documentation-templates'):
        for path in sorted((source/folder).rglob('*')):
            if path.is_file() and '__pycache__' not in path.parts and not path.name.endswith('.pyc'):
                yield path,path.relative_to(source)


def managed_copy(src:Path,dst:Path,root:Path,logs:list[str]):
    if not src.is_file(): raise FileNotFoundError(src)
    for candidate in (dst, *list(dst.parents)):
        if candidate == root.parent:
            break
        if candidate.is_symlink():
            raise ValueError(f'Symlink rejected: {candidate}')
    rendered=asset_bytes(dst,src.read_bytes())
    if dst.exists():
        if dst.read_bytes()==rendered:
            logs.append(f'IGUAL {dst}')
            return
        # Only update content generated by a previous Aikya version.
        marker=root/'manifest.json'
        if not marker.is_file():
            logs.append(f'PRESERVED CUSTOM {dst}')
            return
        previous=json.loads(marker.read_text(encoding='utf8')).get('files',{})
        key=dst.relative_to(root).as_posix()
        old=previous.get(key)
        if not old or hashlib.sha256(dst.read_bytes()).hexdigest()!=old:
            logs.append(f'CONSERVADO PERSONALIZADO {dst}')
            return
    dst.parent.mkdir(parents=True,exist_ok=True)
    dst.write_bytes(rendered)
    shutil.copymode(src,dst)
    logs.append(f'INSTALADO {dst}')


def verified_skill_upgrade(destination,source,previous_hash=None):
    """A marker is not proof of ownership after local editing."""
    from docs_migration_hashes import ASSETS
    raw=destination.read_bytes();digest=hashlib.sha256(raw).hexdigest()
    record=ASSETS.get('.claude/skills/'+destination.parent.name+'/SKILL.md',{})
    return raw==asset_bytes(destination,source.read_bytes()) or digest==previous_hash or digest==record.get('sha256') or digest in record.get('variants',{})

def register_startup_hook(settings:Path, command:str, logs:list[str]) -> None:
    """Merge a lightweight project-discovery hook without clobbering user settings."""
    if settings.is_symlink():
        logs.append(f'NOTICE: symlinked configuration preserved: {settings}')
        return
    try:
        user=json.loads(settings.read_text(encoding='utf8')) if settings.exists() else {}
        if not isinstance(user,dict) or not isinstance(user.get('hooks',{}),dict):
            raise ValueError('invalid settings')
    except (ValueError,UnicodeError,OSError):
        logs.append(f'NOTICE: invalid settings; install hook manually: {settings}')
        return
    hooks=user.setdefault('hooks',{})
    session=hooks.setdefault('SessionStart',[])
    if not isinstance(session,list):
        logs.append(f'NOTICE: invalid hooks.SessionStart: {settings}')
        return
    # Avoid hook duplication when setup runs twice.
    if not any('aikya_session.py' in str(h.get('command',''))
               for group in session if isinstance(group,dict)
               for h in group.get('hooks',[]) if isinstance(h,dict)):
        session.append({'matcher':'startup','hooks':[{'type':'command','command':command,'timeout':5}]})
        settings.parent.mkdir(parents=True,exist_ok=True)
        settings.write_text(json.dumps(user,indent=2,ensure_ascii=False)+'\n',encoding='utf8')
        logs.append(f'SessionStart hook added: {settings}')


# Remove older command assets only when they exactly match the managed historical template.
# Never implicitly delete a user-modified skill.
LEGACY_RENAMES={
    'aikya-project-bootstrap':'aikya-infra-project',
    'aikya-skills':'aikya-skills-status',
}

def retire_legacy_commands(skill_root: Path, runtime: Path, logs: list[str]) -> None:
    for name,replacement in LEGACY_RENAMES.items():
        legacy=skill_root/name/'SKILL.md'
        older=runtime/'bootstrap_skills'/name/'SKILL.md'
        if not legacy.exists() or legacy.is_symlink():
            continue
        if not older.is_file() or older.is_symlink() or legacy.read_bytes()!=older.read_bytes():
            logs.append(f'PRESERVED old customized command /{name}; review migration to /{replacement}')
            continue
        legacy.unlink()
        try: legacy.parent.rmdir()
        except OSError: pass
        logs.append(f'RETIRADO comando gestionado antiguo /{name}; sustituido por /{replacement}')

def migrate_legacy_runtime_skills(runtime: Path, previous: dict[str, str], logs: list[str]) -> None:
    """Remove only verifiably managed skills from the former runtime directory.

    The active commands in .claude/skills are NOT moved or deleted here.
    Customized, untracked and symlinked legacy files are preserved.
    """
    legacy_root = runtime / 'bootstrap_skills'
    if not legacy_root.exists() and not legacy_root.is_symlink():
        return
    if legacy_root.is_symlink() or not legacy_root.is_dir():
        logs.append(f'PRESERVED non-regular legacy directory: {legacy_root}')
        return
    for name in sorted(set(BOOTSTRAP_COMMANDS) | set(LEGACY_RENAMES)):
        folder = legacy_root / name
        skill = folder / 'SKILL.md'
        if folder.is_symlink() or not folder.is_dir() or skill.is_symlink() or not skill.is_file():
            continue
        key = skill.relative_to(runtime).as_posix()
        recorded = previous.get(key)
        raw = skill.read_bytes()
        if not recorded or hashlib.sha256(raw).hexdigest() != recorded or b'AIKYA BOOTSTRAP MANAGED' not in raw:
            logs.append(f'PRESERVED customized or unverified legacy asset: {skill}')
            continue
        # Do not remove an entire folder if it contains other user files.
        skill.unlink()
        previous.pop(key, None)
        try:
            folder.rmdir()
        except OSError:
            pass
        logs.append(f'MIGRADO a aikya-skills/ (runtime anterior retirado): {skill}')
    try:
        legacy_root.rmdir()
    except OSError:
        logs.append(f'PRESERVED additional legacy content: {legacy_root}')


def managed_bootstrap_settings(root):
    marker=root/'.aikya/bootstrap.json';settings=root/'.claude/settings.json'
    if any(p.is_symlink() for p in (marker,marker.parent,settings,settings.parent)):return False
    try:
        data=json.loads(marker.read_text())
        return data.get('_generated_by')=='aikya-setup' and data.get('managed_settings_sha256')==hashlib.sha256(settings.read_bytes()).hexdigest()
    except (ValueError,OSError,AttributeError):return False

def setup(source:Path,target:Path,scope:str,home:Path|None=None,dry_run:bool=False,subagent_statusline:bool=False)->list[str]:
    source=source.resolve()
    target=target.expanduser().resolve()
    home=(home or Path.home()).expanduser().resolve()
    if scope not in ('global','project'):raise ValueError('scope debe ser global o project')
    if not (source/'install.py').is_file() or any(not (source/'aikya-skills'/name/'SKILL.md').is_file() for name in BOOTSTRAP_COMMANDS):
        raise ValueError('Source is not a complete Aikya distribution')
    runtime=(home/'.claude/aikya-harnes') if scope=='global' else (target/'.aikya/runtime')
    skill_root=(home/'.claude/skills') if scope=='global' else (target/'.claude/skills')
    for candidate in (runtime, runtime.parent, skill_root, skill_root.parent):
        if candidate.is_symlink():
            raise ValueError(f'Symlinked directories are not supported: {candidate}')
    settings_path=(home if scope=='global' else target)/'.claude/settings.json'
    settings_created=not settings_path.exists()
    settings_owned=managed_bootstrap_settings(target) if scope=='project' else False
    operations=list(files_to_copy(source))
    logs=[f'AIKYA SCOPE={scope} runtime={runtime} skills={skill_root}']
    if dry_run:
        logs.append(f'PLAN: {len(operations)} runtime files and {len(BOOTSTRAP_COMMANDS)} skills; no interview or external download')
        return logs
    runtime.mkdir(parents=True,exist_ok=True)
    old_manifest={}
    if (runtime/'manifest.json').is_file():
        try:
            old_manifest=json.loads((runtime/'manifest.json').read_text(encoding='utf8')).get('files',{})
            if not isinstance(old_manifest, dict):
                old_manifest={}
        except (ValueError,OSError):
            old_manifest={}
    retire_legacy_commands(skill_root,runtime,logs)
    migrate_legacy_runtime_skills(runtime,old_manifest,logs)
    new_manifest=dict(old_manifest)
    for src,rel in operations:
        dst=runtime/rel
        managed_copy(src,dst,runtime,logs)
        written=dst.read_bytes()
        if written==asset_bytes(dst,src.read_bytes()):
            new_manifest[rel.as_posix()]=hashlib.sha256(written).hexdigest()
    (runtime/'manifest.json').write_text(json.dumps({'_generated_by':'aikya-setup','files':new_manifest},indent=2)+'\n',encoding='utf8')
    for name in BOOTSTRAP_COMMANDS:
        src=source/'aikya-skills'/name/'SKILL.md'
        dst=skill_root/name/'SKILL.md'
        if dst.is_symlink() or dst.parent.is_symlink():
            raise ValueError(f'Symlinked skill is not allowed: {dst}')
        rendered=asset_bytes(dst,src.read_bytes())
        if dst.exists() and dst.read_bytes()!=rendered:
            # Only replace our own previous generated bootstrap skills.
            if not verified_skill_upgrade(dst,src,old_manifest.get('aikya-skills/'+name+'/SKILL.md')):
                logs.append(f'PRESERVED customized skill: {dst}')
                continue
        dst.parent.mkdir(parents=True,exist_ok=True)
        dst.write_bytes(rendered)
        shutil.copymode(src,dst)
        logs.append(f'SKILL disponible: /{name} ({scope})')
    if scope=='global':
        command='python3 -B '+shlex.quote(str(runtime/'aikya_session.py'))
        register_startup_hook(home/'.claude/settings.json',command,logs)
    else:
        command='python3 "${CLAUDE_PROJECT_DIR}/.aikya/runtime/aikya_session.py"'
        register_startup_hook(target/'.claude/settings.json',command,logs)
    from execution_config import register_visibility
    observer='python3 -B '+shlex.quote(str(runtime/'execution_observer.py'))+' hook'
    bar='python3 -B '+shlex.quote(str(runtime/'aikya_statusline.py'))
    register_visibility((home if scope=='global' else target)/'.claude/settings.json',observer,bar,logs,(home/'.claude' if scope=='global' else target/'.aikya')/'visibility-proposed.json',subagent_command=('python3 -B '+__import__('shlex').quote(str(runtime/'aikya_subagent_statusline.py'))) if subagent_statusline else None)
    if scope=='project':
        marker=target/'.aikya/bootstrap.json' 
        marker.parent.mkdir(parents=True,exist_ok=True)
        if not marker.exists() or settings_created or settings_owned:
            if marker.is_symlink():raise ValueError('Symlinked bootstrap marker')
            payload={'_generated_by':'aikya-setup','scope':'project','runtime':'.aikya/runtime'}
            if settings_created or settings_owned:payload['managed_settings_sha256']=hashlib.sha256(settings_path.read_bytes()).hexdigest()
            marker.write_text(json.dumps(payload,indent=2)+'\n',encoding='utf8')
    return logs


def main(argv=None):
    p=argparse.ArgumentParser(description='Aikya Harness registration within Claude Code')
    p.add_argument('--scope',choices=['global','project'],required=True)
    p.add_argument('--target',type=Path,default=Path.cwd(),help='Directorio de trabajo actual, cuando scope=project')
    p.add_argument('--subagent-statusline',action='store_true',help='Enable only on a client supporting subagentStatusLine')
    p.add_argument('--dry-run',action='store_true')
    args=p.parse_args(argv)
    try:
        for line in setup(ROOT,args.target,args.scope,dry_run=args.dry_run,subagent_statusline=args.subagent_statusline): print(line)
    except (OSError,ValueError) as exc:
        print(f'ERROR: {exc}',file=sys.stderr)
        return 1
    print('Next: in Claude Code use /aikya-init (nuevo), /aikya-analyze (existente), /aikya-answers, /aikya-scaffold, /aikya-skills-status o /aikya-quality.')
    return 0

if __name__=='__main__':sys.exit(main())
